//! Generates app/src/generated/core.d.ts (ts-rs) and core.schema.json (schemars). `cargo run -p swift-canvas-core --example gen` writes them; `--check` fails if they differ (a test does this).
use schemars::schema_for;
use swift_canvas_core::{FlatNode, Node, Op, OpError, Tree};
use ts_rs::TS;
pub fn ts() -> String {
    let mut s = String::from("// GENERATED by `cargo run -p swift-canvas-core --example gen` from core/src/lib.rs. Do not edit.\n");
    for d in [Node::decl(), Tree::decl(), FlatNode::decl(), Op::decl(), OpError::decl()] { s.push_str("export "); s.push_str(&d); s.push('\n'); }
    s
}
pub fn schema() -> String {
    let all = serde_json::json!({ "$comment": "GENERATED from core/src/lib.rs", "Op": schema_for!(Op), "Tree": schema_for!(Tree), "Node": schema_for!(Node), "FlatNode": schema_for!(FlatNode), "OpError": schema_for!(OpError) });
    serde_json::to_string_pretty(&all).unwrap() + "\n"
}
fn main() {
    let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../app/src/generated");
    let (a, b) = (ts(), schema());
    if std::env::args().any(|x| x == "--check") { let ok = std::fs::read_to_string(dir.join("core.d.ts")).ok().as_deref() == Some(a.as_str()) && std::fs::read_to_string(dir.join("core.schema.json")).ok().as_deref() == Some(b.as_str()); if !ok { eprintln!("generated files are stale: run cargo run -p swift-canvas-core --example gen"); std::process::exit(1); } return; }
    std::fs::create_dir_all(&dir).unwrap(); std::fs::write(dir.join("core.d.ts"), a).unwrap(); std::fs::write(dir.join("core.schema.json"), b).unwrap();
}
